-- The weekly goal each week had, so the streak judges a past week by the
-- goal set then, not today's (WeeklyGoals). One row per account and week
-- the goal was changed in (Monday start); a null goal means none (one
-- workout a week). A week uses the latest row at or before it.
create table weekly_goal_change (
    id bigint generated by default as identity,
    user_id bigint not null,
    week_start date not null,
    weekly_goal integer,
    primary key (id),
    constraint fk_weekly_goal_change_user foreign key (user_id) references app_user,
    constraint uk_weekly_goal_change_week unique (user_id, week_start)
);

-- Today's goals cover every week so far (3 Jan 2000 is a Monday, before
-- anyone could have logged), so no one's streak changes with this.
insert into weekly_goal_change (user_id, week_start, weekly_goal)
    select user_id, date '2000-01-03', weekly_goal from user_profile where weekly_goal is not null;
