-- A workout's repeating plan (WorkoutRepeat). Either weekly on a set of
-- days (weekdays: bit 0 = Monday ... bit 6 = Sunday) or every N days
-- counted from start_date. Planned days are worked out when asked for,
-- not stored; a scheduled_workout row saved for a day overrides the rule
-- on that day. Editing a rule ends the old row and starts a new one, so a
-- workout has many rows over time but at most one covering any date.
create table workout_repeat (
    id bigint generated by default as identity,
    user_id bigint not null,
    workout_id bigint not null,
    start_date date not null,
    end_date date,
    weekdays integer,
    every_days integer,
    created_at timestamp(6),
    primary key (id),
    constraint fk_workout_repeat_user foreign key (user_id) references app_user,
    constraint fk_workout_repeat_workout foreign key (workout_id) references workout,
    constraint ck_workout_repeat_kind check (
        (weekdays is not null and every_days is null and weekdays between 1 and 127)
        or (weekdays is null and every_days is not null and every_days >= 1)),
    constraint ck_workout_repeat_dates check (end_date is null or end_date >= start_date)
);

create index ix_workout_repeat_user on workout_repeat (user_id);
create index ix_workout_repeat_workout on workout_repeat (workout_id);
