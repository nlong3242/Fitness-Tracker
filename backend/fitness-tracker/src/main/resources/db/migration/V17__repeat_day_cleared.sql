-- A repeat day whose calendar entry was deleted (RepeatDayCleared). The rule
-- would otherwise plan that day again, because nothing saved covers it any more.
create table repeat_day_cleared (
    id bigint generated by default as identity,
    user_id bigint not null,
    workout_id bigint not null,
    cleared_date date not null,
    primary key (id),
    constraint fk_repeat_day_cleared_user foreign key (user_id) references app_user,
    constraint fk_repeat_day_cleared_workout foreign key (workout_id) references workout,
    constraint uk_repeat_day_cleared unique (workout_id, cleared_date)
);

create index ix_repeat_day_cleared_user on repeat_day_cleared (user_id, cleared_date);
