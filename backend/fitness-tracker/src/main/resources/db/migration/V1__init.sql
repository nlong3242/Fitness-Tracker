create table exercise (
    id bigint generated by default as identity,
    name varchar(255),
    category enum ('ARMS','BACK','CHEST','CORE','LEGS','SHOULDERS'),
    primary_muscle_groups varchar(255),
    exercise_type varchar(255),
    cues varchar(1000),
    notes varchar(5000),
    unilateral boolean,
    deleted boolean not null,
    primary key (id)
);

create table workout (
    id bigint generated by default as identity,
    name varchar(255),
    primary key (id)
);

create table workout_exercise (
    id bigint generated by default as identity,
    workout_id bigint,
    exercise_id bigint,
    position integer not null,
    primary key (id),
    constraint uk_workout_exercise_workout_exercise unique (workout_id, exercise_id)
);

create table session (
    id bigint generated by default as identity,
    date date,
    finished boolean not null,
    workout_id bigint,
    primary key (id)
);

create table exercise_set (
    id bigint generated by default as identity,
    weight float(53) not null,
    reps integer not null,
    side enum ('LEFT','RIGHT'),
    exercise_id bigint,
    session_id bigint,
    primary key (id)
);

create table session_exercise (
    id bigint generated by default as identity,
    session_id bigint,
    exercise_id bigint,
    position integer not null,
    name varchar(255),
    category enum ('ARMS','BACK','CHEST','CORE','LEGS','SHOULDERS'),
    primary_muscle_groups varchar(255),
    exercise_type varchar(255),
    cues varchar(1000),
    unilateral boolean,
    primary key (id)
);

create table scheduled_workout (
    id bigint generated by default as identity,
    date date,
    workout_id bigint,
    status enum ('COMPLETED','PLANNED','SKIPPED'),
    session_id bigint unique,
    notes varchar(255),
    created_at timestamp(6),
    primary key (id),
    constraint uk_scheduled_workout_date_workout unique (date, workout_id)
);

alter table exercise_set add constraint fk_exercise_set_exercise foreign key (exercise_id) references exercise;
alter table exercise_set add constraint fk_exercise_set_session foreign key (session_id) references session;
alter table session add constraint fk_session_workout foreign key (workout_id) references workout;
alter table session_exercise add constraint fk_session_exercise_exercise foreign key (exercise_id) references exercise;
alter table session_exercise add constraint fk_session_exercise_session foreign key (session_id) references session;
alter table scheduled_workout add constraint fk_scheduled_workout_session foreign key (session_id) references session;
alter table scheduled_workout add constraint fk_scheduled_workout_workout foreign key (workout_id) references workout;
alter table workout_exercise add constraint fk_workout_exercise_exercise foreign key (exercise_id) references exercise;
alter table workout_exercise add constraint fk_workout_exercise_workout foreign key (workout_id) references workout;
