-- Accounts. Passwords are stored as BCrypt hashes. A login token is a
-- random value only the client holds; the table keeps its SHA-256, so a
-- copy of this table can't be used to log in. A token lapses 90 days after
-- last_used_at (AuthService). Profile details (name, age...) will get their
-- own table.
create table app_user (
    id bigint generated by default as identity,
    email varchar(254) not null,
    password_hash varchar(100) not null,
    created_at timestamp(6) not null,
    primary key (id),
    constraint uk_app_user_email unique (email)
);

create table auth_token (
    id bigint generated by default as identity,
    user_id bigint not null,
    token_hash varchar(64) not null,
    created_at timestamp(6) not null,
    last_used_at timestamp(6) not null,
    primary key (id),
    constraint uk_auth_token_hash unique (token_hash),
    constraint fk_auth_token_user foreign key (user_id) references app_user
);
